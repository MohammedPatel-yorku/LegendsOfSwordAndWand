package com.university.project.legendsofswordandwand.model.enums;

/**
 * Represents the two types of rooms a player can encounter while progressing through the PvE
 * dungeon campaign.
 */
public enum RoomType {
  /** A combat encounter — the player enters a battle with a randomly generated enemy party. */
  BATTLE,
  /** A rest stop — the player's party is healed and they may shop or recruit new heroes. */
  INN
}
